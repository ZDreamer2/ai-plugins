"""Collect and format Codex and Pi adaptation backlogs without writing files."""

from collections.abc import Iterable
from typing import Generic, TypeVar

from .rendering import (
    CodexConstruct, CodexConstructFinding, PiConstruct, PiConstructFinding,
)


_Finding = TypeVar("_Finding", CodexConstructFinding, PiConstructFinding)


def _note(files: dict[str, list[_Finding]]) -> str:
    count = sum(len(findings) for findings in files.values())
    return f"{count} unresolved construct(s) in {len(files)} file(s)"


class _ReportSections(Generic[_Finding]):
    """Retain first nonempty copies and attribute shared paths to their origin."""

    COMMON_SECTION = "@common"
    ROOT_SECTION = "@root"

    def __init__(self) -> None:
        self._sections: dict[str, dict[str, list[_Finding]]] = {}

    def add(
        self, logical_path: str, plugin_root: str | None,
        findings: Iterable[_Finding],
    ) -> None:
        entries = list(findings)
        if not entries:
            return
        common_at = logical_path.find(self.COMMON_SECTION + "/")
        if common_at < 0:
            section = self.ROOT_SECTION if plugin_root is None else plugin_root
            path = logical_path
        else:
            section = self.COMMON_SECTION
            path = logical_path[common_at:]
        self._sections.setdefault(section, {}).setdefault(path, entries)

    def sorted(self) -> dict[str, dict[str, list[_Finding]]]:
        special = (self.COMMON_SECTION, self.ROOT_SECTION)
        order = sorted(section for section in self._sections if section not in special)
        order.extend(section for section in special if section in self._sections)
        return {
            section: dict(sorted(self._sections[section].items()))
            for section in order
        }

    def summaries(self) -> dict[str, str]:
        return {section: _note(files) for section, files in self.sorted().items()}

    def total(self) -> str:
        # PHP array_merge replaces overlapping string paths in section insertion
        # order; sorted presentation must not change which copy contributes here.
        files: dict[str, list[_Finding]] = {}
        for section_files in self._sections.values():
            files.update(section_files)
        return _note(files)


def _category_lines(
    files: dict[str, list[_Finding]],
    categories: Iterable[CodexConstruct | PiConstruct],
) -> list[str]:
    lines: list[str] = []
    for category in categories:
        entries = [
            f"- {path}:{finding.line} — {finding.text}"
            for path, findings in files.items()
            for finding in findings
            if finding.category is category
        ]
        if entries:
            lines.extend(("", f"### {category.title()} ({len(entries)})", ""))
            lines.extend(entries)
    return lines


class CodexConstructReport:
    """Collect Codex findings by origin, retaining the first nonempty copy."""

    COMMON_SECTION = _ReportSections.COMMON_SECTION
    ROOT_SECTION = _ReportSections.ROOT_SECTION

    def __init__(self) -> None:
        self._sections = _ReportSections[CodexConstructFinding]()

    def add(
        self, logical_path: str, plugin_root: str | None,
        findings: Iterable[CodexConstructFinding],
    ) -> None:
        self._sections.add(logical_path, plugin_root, findings)

    def summaries(self) -> dict[str, str]:
        return self._sections.summaries()

    def total(self) -> str:
        return self._sections.total()

    def render(self) -> str:
        lines = [
            "# Unresolved Claude constructs in the Codex tree",
            "",
            "Everything the Codex render leaves literal, per plugin, with `@common` listed once under",
            "the origin path every plugin copies it from. Generated by the build; nothing here fails it.",
            "",
            'Lines are the rendered file\'s, except under "Skill frontmatter": the render has removed the key by',
            "then, so those point at the source `SKILL.md`.",
        ]
        for section, files in self._sections.sorted().items():
            lines.extend(("", f"## {section} — {_note(files)}"))
            lines.extend(_category_lines(files, CodexConstruct))
        return "\n".join(lines) + "\n"


class PiConstructReport:
    """Collect report-only Pi findings with rendered line numbers."""

    COMMON_SECTION = _ReportSections.COMMON_SECTION
    ROOT_SECTION = _ReportSections.ROOT_SECTION

    def __init__(self) -> None:
        self._sections = _ReportSections[PiConstructFinding]()

    def add(
        self, logical_path: str, plugin_root: str | None,
        findings: Iterable[PiConstructFinding],
    ) -> None:
        self._sections.add(logical_path, plugin_root, findings)

    def summaries(self) -> dict[str, str]:
        return self._sections.summaries()

    def total(self) -> str:
        return self._sections.total()

    def render(self) -> str:
        lines = [
            "# Unresolved host constructs in the Pi tree",
            "",
            "Everything the Pi render leaves literal, per plugin, with `@common` listed once under its origin path.",
            "Generated by the build; findings are an adaptation backlog and do not fail it.",
            "Line numbers refer to rendered Pi files; `@common` paths name the shared source to edit.",
        ]
        for section, files in self._sections.sorted().items():
            lines.extend(("", f"## {section} — {_note(files)}"))
            lines.extend(_category_lines(files, PiConstruct))
        return "\n".join(lines) + "\n"
