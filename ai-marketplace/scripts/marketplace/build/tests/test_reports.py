"""Independent PHP-derived report snapshots and attribution expectations."""

from pathlib import Path
import tempfile
import unittest

from marketplace.build import CodexConstructReport, PiConstructReport
from marketplace.build.rendering import (
    CodexConstruct, CodexConstructFinding, PiConstruct, PiConstructFinding,
    preflight_pi, render_file_result,
)
from marketplace.source import discover_source, plugin_root_of


_HEADER = (
    "# Unresolved Claude constructs in the Codex tree\n\n"
    "Everything the Codex render leaves literal, per plugin, with `@common` listed once under\n"
    "the origin path every plugin copies it from. Generated by the build; nothing here fails it.\n\n"
    'Lines are the rendered file\'s, except under "Skill frontmatter": the render has removed the key by\n'
    "then, so those point at the source `SKILL.md`.\n"
)

_PI_HEADER = (
    "# Unresolved host constructs in the Pi tree\n\n"
    "Everything the Pi render leaves literal, per plugin, with `@common` listed once under its origin path.\n"
    "Generated by the build; findings are an adaptation backlog and do not fail it.\n"
    "Line numbers refer to rendered Pi files; `@common` paths name the shared source to edit.\n"
)


def finding(category: CodexConstruct, line: int, text: str) -> CodexConstructFinding:
    return CodexConstructFinding(category, line, text)


def pi_finding(category: PiConstruct, line: int, text: str) -> PiConstructFinding:
    return PiConstructFinding(category, line, text)


class ReportTests(unittest.TestCase):
    def test_exact_report_snapshot_and_summary_order(self) -> None:
        report = CodexConstructReport()
        report.add("README.md", None, [finding(CodexConstruct.SKILL_INVOCATION, 2, "/deep")])
        report.add("main/@common/docs/Shared.md", "main", [finding(CodexConstruct.CLAUDE_TOOL, 3, "AskUserQuestion")])
        report.add("main/skills/quiet/SKILL.md", "main", [
            finding(CodexConstruct.SKILL_FRONTMATTER, 5, "user-invocable: false"),
            finding(CodexConstruct.SKILL_FRONTMATTER, 6, "model: sonnet"),
        ])
        report.add("main/skills/deep/SKILL.md", "main", [
            finding(CodexConstruct.SKILL_INVOCATION, 18, "slash command"),
            finding(CodexConstruct.CROSS_PLUGIN_REFERENCE, 19, "AI_DOC_PLUGIN/Formats/x.md"),
            finding(CodexConstruct.CLAUDE_VARIABLE, 13, "${CLAUDE_PLUGIN_ROOT}"),
            finding(CodexConstruct.CLAUDE_VARIABLE, 13, "${CLAUDE_SKILL_DIR}"),
            finding(CodexConstruct.CLAUDE_TOOL, 18, "AskUserQuestion"),
            finding(CodexConstruct.CLAUDE_VARIABLE, 19, "$ARGUMENTS"),
            finding(CodexConstruct.SKILL_INVOCATION, 19, "/deep"),
        ])
        report.add("dev/other/README.md", "dev/other", [finding(CodexConstruct.CLAUDE_TOOL, 1, "AskUserQuestion")])
        report.add("dev/other/@common/docs/Shared.md", "dev/other", [finding(CodexConstruct.CLAUDE_VARIABLE, 9, "$ARGUMENTS")])
        self.assertEqual(report.render(), _HEADER + (
            "\n## dev/other — 1 unresolved construct(s) in 1 file(s)\n"
            "\n### Claude tool names and arguments (1)\n\n"
            "- dev/other/README.md:1 — AskUserQuestion\n"
            "\n## main — 9 unresolved construct(s) in 2 file(s)\n"
            "\n### Claude variables (3)\n\n"
            "- main/skills/deep/SKILL.md:13 — ${CLAUDE_PLUGIN_ROOT}\n"
            "- main/skills/deep/SKILL.md:13 — ${CLAUDE_SKILL_DIR}\n"
            "- main/skills/deep/SKILL.md:19 — $ARGUMENTS\n"
            "\n### Claude tool names and arguments (1)\n\n"
            "- main/skills/deep/SKILL.md:18 — AskUserQuestion\n"
            "\n### Skill invocation wording (2)\n\n"
            "- main/skills/deep/SKILL.md:18 — slash command\n"
            "- main/skills/deep/SKILL.md:19 — /deep\n"
            "\n### Cross-plugin references (1)\n\n"
            "- main/skills/deep/SKILL.md:19 — AI_DOC_PLUGIN/Formats/x.md\n"
            "\n### Skill frontmatter (2)\n\n"
            "- main/skills/quiet/SKILL.md:5 — user-invocable: false\n"
            "- main/skills/quiet/SKILL.md:6 — model: sonnet\n"
            "\n## @common — 1 unresolved construct(s) in 1 file(s)\n"
            "\n### Claude tool names and arguments (1)\n\n"
            "- @common/docs/Shared.md:3 — AskUserQuestion\n"
            "\n## @root — 1 unresolved construct(s) in 1 file(s)\n"
            "\n### Skill invocation wording (1)\n\n"
            "- README.md:2 — /deep\n"
        ))
        self.assertEqual(list(report.summaries().items()), [
            ("dev/other", "1 unresolved construct(s) in 1 file(s)"),
            ("main", "9 unresolved construct(s) in 2 file(s)"),
            ("@common", "1 unresolved construct(s) in 1 file(s)"),
            ("@root", "1 unresolved construct(s) in 1 file(s)"),
        ])
        self.assertEqual(report.total(), "12 unresolved construct(s) in 5 file(s)")

    def test_empty_reports_and_first_nonempty_retention(self) -> None:
        report = CodexConstructReport()
        report.add("empty.md", "empty", [])
        self.assertEqual(report.render(), _HEADER)
        self.assertEqual(report.summaries(), {})
        self.assertEqual(report.total(), "0 unresolved construct(s) in 0 file(s)")
        original = finding(CodexConstruct.CLAUDE_TOOL, 1, "TaskList")
        findings = [original, original]
        report.add("copy/@common/docs/x.md", "copy", [])
        report.add("copy/@common/docs/x.md", "copy", findings)
        findings.clear()
        report.add("other/@common/docs/x.md", "other", [finding(CodexConstruct.CLAUDE_VARIABLE, 8, "$ARGUMENTS")])
        self.assertEqual(report.summaries(), {"@common": "2 unresolved construct(s) in 1 file(s)"})
        self.assertEqual(report.total(), "2 unresolved construct(s) in 1 file(s)")
        self.assertEqual(report.render().count("- @common/docs/x.md:1 — TaskList\n"), 2)
        self.assertNotIn("$ARGUMENTS", report.render())

    def test_substring_origin_first_marker_and_literal_path_sorting(self) -> None:
        report = CodexConstructReport()
        item = finding(CodexConstruct.CLAUDE_TOOL, 1, "TaskList")
        for path in ("plugin/b.md", "plugin/a.md"):
            report.add(path, "plugin", [item])
        report.add("prefix-not-a-segment@common/a/@common/x.md", "plugin", [item])
        report.add("@common/no-owner.md", None, [item])
        report.add("outside.md", None, [item])
        report.add("empty-plugin.md", "", [item])
        self.assertEqual(list(report.summaries()), ["", "plugin", "@common", "@root"])
        markdown = report.render()
        self.assertLess(markdown.index("- plugin/a.md"), markdown.index("- plugin/b.md"))
        self.assertIn("- @common/a/@common/x.md:1 — TaskList", markdown)
        self.assertNotIn("prefix-not-a-segment", markdown)

    def test_total_cross_section_key_merge_uses_section_insertion_order(self) -> None:
        item = finding(CodexConstruct.CLAUDE_TOOL, 1, "TaskList")
        report = CodexConstructReport()
        report.add("overlap.md", "z", [item, item, item])
        report.add("overlap.md", "a", [item])
        # Adding a new path to the first section does not move that section later.
        report.add("extra.md", "z", [item])
        self.assertEqual(report.summaries(), {
            "a": "1 unresolved construct(s) in 1 file(s)",
            "z": "4 unresolved construct(s) in 2 file(s)",
        })
        self.assertEqual(report.total(), "2 unresolved construct(s) in 2 file(s)")
        opposite = CodexConstructReport()
        opposite.add("overlap.md", "a", [item])
        opposite.add("overlap.md", "z", [item, item, item])
        self.assertEqual(opposite.total(), "3 unresolved construct(s) in 1 file(s)")

    def test_rendered_symlink_copies_and_include_findings_use_consuming_path(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            shared = root / "@common/docs"
            shared.mkdir(parents=True)
            (shared / "Shared.md").write_text(
                "Before\n${AGENT_INCLUDE_DOC_FOR(codex, Selected.md)}\nAfter\n",
                encoding="utf-8",
            )
            (shared / "Selected.md").write_text(
                "${AGENT_QUESTION_TOOL} $ARGUMENTS\n", encoding="utf-8",
            )
            for name in ("second", "first"):
                plugin = root / name
                plugin.mkdir()
                (plugin / "ai-plugin.yml").write_text(f"description: {name}\n", encoding="utf-8")
                (plugin / "@common").symlink_to("../@common", target_is_directory=True)
            before = {path: path.read_bytes() for path in root.rglob("*") if path.is_file()}
            source = discover_source(root)
            report = CodexConstructReport()
            for name in ("second", "first"):
                path = f"{name}/@common/docs/Shared.md"
                result = render_file_result((root / path).read_text(encoding="utf-8"), path, "codex", source)
                self.assertEqual(result.content, "Before\nrequest_user_input_async $ARGUMENTS\nAfter\n")
                self.assertEqual(result.findings, [
                    finding(CodexConstruct.CLAUDE_VARIABLE, 2, "$ARGUMENTS"),
                ])
                report.add(path, plugin_root_of(source, path), result.findings)
            self.assertEqual(report.summaries(), {"@common": "1 unresolved construct(s) in 1 file(s)"})
            self.assertEqual(report.total(), "1 unresolved construct(s) in 1 file(s)")
            self.assertEqual(report.render(), _HEADER + (
                "\n## @common — 1 unresolved construct(s) in 1 file(s)\n"
                "\n### Claude variables (1)\n\n"
                "- @common/docs/Shared.md:2 — $ARGUMENTS\n"
            ))
            after = {path: path.read_bytes() for path in root.rglob("*") if path.is_file()}
            self.assertEqual(after, before)
            self.assertTrue((root / "first/@common").is_symlink())
            self.assertFalse((root / "codex-report.md").exists())


