    def test_pi_rendered_symlink_copies_includes_and_report_only_preflight(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            shared = root / "@common/docs"
            shared.mkdir(parents=True)
            (shared / "Shared.md").write_text(
                "Before\n${AGENT_INCLUDE_DOC_FOR(pi, Selected.md)}\nAfter\n",
                encoding="utf-8",
            )
            (shared / "Selected.md").write_text(
                "${AGENT_QUESTION_TOOL} spawn_agent $ARGUMENTS\n", encoding="utf-8",
            )
            for name in ("second", "first"):
                plugin = root / name
                (plugin / "skills/run").mkdir(parents=True)
                (plugin / "ai-plugin.yml").write_text(f"description: {name}\n", encoding="utf-8")
                (plugin / "@common").symlink_to("../@common", target_is_directory=True)
                (plugin / "skills/run/SKILL.md").write_text(
                    "---\nname: run\ndescription: Test\n---\nTaskList $123\n",
                    encoding="utf-8",
                )
            before = {path: path.read_bytes() for path in root.rglob("*") if path.is_file()}
            source = discover_source(root)
            preflight_pi(source)
            report = PiConstructReport()
            for name in ("second", "first"):
                path = f"{name}/@common/docs/Shared.md"
                result = render_file_result((root / path).read_text(encoding="utf-8"), path, "pi", source)
                self.assertEqual(result.content, "Before\nask_user_question spawn_agent $ARGUMENTS\nAfter\n")
                self.assertEqual(result.extra_files, {})
                self.assertEqual(result.findings, [
                    pi_finding(PiConstruct.HOST_VARIABLE, 2, "$ARGUMENTS"),
                    pi_finding(PiConstruct.HOST_TOOL, 2, "spawn_agent"),
                ])
                report.add(path, plugin_root_of(source, path), result.findings)
            self.assertEqual(report.summaries(), {"@common": "2 unresolved construct(s) in 1 file(s)"})
            self.assertEqual(report.total(), "2 unresolved construct(s) in 1 file(s)")
            self.assertEqual(report.render(), _PI_HEADER + (
                "\n## @common — 2 unresolved construct(s) in 1 file(s)\n"
                "\n### Host variables and roots (1)\n\n"
                "- @common/docs/Shared.md:2 — $ARGUMENTS\n"
                "\n### Host tool names and arguments (1)\n\n"
                "- @common/docs/Shared.md:2 — spawn_agent\n"
            ))
            after = {path: path.read_bytes() for path in root.rglob("*") if path.is_file()}
            self.assertEqual(after, before)
            self.assertTrue((root / "first/@common").is_symlink())
            self.assertFalse((root / "pi-report.md").exists())


