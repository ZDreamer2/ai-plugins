    def test_empty_first_nonempty_copy_duplicates_and_instance_independence(self) -> None:
        report = PiConstructReport()
        report.add("empty.md", "empty", [])
        self.assertEqual(report.render(), _PI_HEADER)
        self.assertEqual(report.summaries(), {})
        self.assertEqual(report.total(), "0 unresolved construct(s) in 0 file(s)")
        item = pi_finding(PiConstruct.HOST_TOOL, 1, "TaskList")
        entries = [item, item]
        report.add("copy/@common/docs/x.md", "copy", [])
        report.add("copy/@common/docs/x.md", "copy", iter(entries))
        entries.clear()
        report.add("other/@common/docs/x.md", "other", [pi_finding(PiConstruct.HOST_VARIABLE, 8, "$ARGUMENTS")])
        self.assertEqual(report.summaries(), {"@common": "2 unresolved construct(s) in 1 file(s)"})
        self.assertEqual(report.total(), "2 unresolved construct(s) in 1 file(s)")
        self.assertEqual(report.render().count("- @common/docs/x.md:1 — TaskList\n"), 2)
        self.assertNotIn("$ARGUMENTS", report.render())
        report.summaries().clear()
        self.assertEqual(report.total(), "2 unresolved construct(s) in 1 file(s)")
        other = PiConstructReport()
        codex = CodexConstructReport()
        self.assertEqual(other.render(), _PI_HEADER)
        self.assertEqual(codex.render(), _HEADER)
        codex.add("copy/@common/docs/x.md", "copy", [finding(CodexConstruct.CLAUDE_VARIABLE, 9, "$ARGUMENTS")])
        self.assertEqual(codex.total(), "1 unresolved construct(s) in 1 file(s)")
        self.assertEqual(report.total(), "2 unresolved construct(s) in 1 file(s)")
        self.assertEqual(other.total(), "0 unresolved construct(s) in 0 file(s)")

    def test_literal_substring_origins_path_sorting_and_insertion_order_totals(self) -> None:
        item = pi_finding(PiConstruct.HOST_TOOL, 1, "TaskList")
        report = PiConstructReport()
        for path in ("plugin/b.md", "plugin/a.md"):
            report.add(path, "plugin", [item])
        report.add("prefix-not-a-segment@common/a/@common/x.md", "plugin", [item])
        report.add("@common/no-owner.md", None, [item])
        report.add("outside.md", None, [item])
        report.add("empty-plugin.md", "", [item])
