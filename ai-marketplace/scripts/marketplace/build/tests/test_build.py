    def seed_output(self, output: Path | None = None) -> Path:
        output = output or self.source / "@build"
        for host in HOSTS:
            (output / host / "stale-empty").mkdir(parents=True)
            (output / host / "sentinel").write_bytes(host.encode())
        for host in ("codex", "pi"):
            (output / f"{host}-report.md").write_bytes(b"saved report")
        (output / "unrelated.bin").write_bytes(b"keep me")
        return output

    def installer_sources(self, directory: Path) -> None:
        directory.mkdir(parents=True, exist_ok=True)
        sources = {
            "setup.py": (
                b'STATUS_LINE_B64 = "__STATUS_LINE_PLACEHOLDER__"\n'
                b'SETTINGS_B64 = "__SETTINGS_PLACEHOLDER__"\n'
            ),
            "status-line.py": b"print('status')\n",
            "settings.json": b"{}\n",
            "install.sh": (
                b"__INSTALLER_VERSION__\n# === BUNDLE_REPLACE_BEGIN ===\n"
                b"old\n# === BUNDLE_REPLACE_END ===\n"
            ),
            "install.ps1": (
                b"__INSTALLER_VERSION__\n# === BUNDLE_REPLACE_BEGIN ===\n"
                b"old\n# === BUNDLE_REPLACE_END ===\n"
            ),
        }
        for name, content in sources.items():
            path = directory / name
            path.write_bytes(content)
            path.chmod(0o700 if name.endswith(".sh") else 0o600)

