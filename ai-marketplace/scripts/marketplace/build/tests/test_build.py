def json_bytes(value: object) -> bytes:
    """Specify PHP's JSON wire format independently of the production writer."""
    return (json.dumps(value, indent="\t", ensure_ascii=False) + "\n").encode()


def skill(name: str = "run", body: str = "Do the work.\n") -> str:
    return f"---\nname: {name}\ndescription: Useful work.\n---\n{body}"


def snapshot(root: Path, excluded: Path | None = None) -> dict[str, tuple]:
    """Capture bytes, modes, empty directories and links without following them."""
    result: dict[str, tuple] = {}
    if not root.exists():
        return result
    for current, dirs, files in os.walk(root, followlinks=False):
        parent = Path(current)
        if excluded is not None:
            dirs[:] = [name for name in dirs if parent / name != excluded]
        for name in dirs + files:
            path = parent / name
            if path == excluded:
                continue
            relative = path.relative_to(root).as_posix()
            mode = stat.S_IMODE(path.lstat().st_mode)
            if path.is_symlink():
                result[relative] = ("link", mode, os.readlink(path))
            elif path.is_dir():
                result[relative] = ("dir", mode)
            else:
                result[relative] = ("file", mode, path.read_bytes())
    return result


class BuildTests(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.base = Path(temporary.name)
        self.source = self.base / "source"
        self.source.mkdir()

    def write(self, path: str, content: str | bytes, mode: int = 0o640) -> None:
        target = self.source / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content.encode() if isinstance(content, str) else content)
        target.chmod(mode)

    def plugin(self, root: str = "main", manifest: str | None = None) -> None:
        self.write(root + "/ai-plugin.yml", manifest or (
            "name: main\nversion: 1.2.3\ndescription: Main plugin.\n"
        ))

    def test_root_ci_is_source_only_but_plugin_resources_are_retained(self) -> None:
        self.plugin()
        self.write(".gitlab-ci.yml", "source configuration\n")
        self.write(".gitlab/private.md", "${AGENT_SKILL(unpublished)}\n")
        self.write(".github/workflows/build.yml", "source configuration\n")
        self.write("main/.gitlab/resource.txt", "plugin-owned resource\n")
        output = self.base / "output"
        build(self.source, output, now=NOW)
        for host in HOSTS:
            for name in (".gitlab-ci.yml", ".gitlab", ".github"):
                self.assertFalse((output / host / name).exists())
            self.assertEqual(
                (output / host / "main/.gitlab/resource.txt").read_text(),
                "plugin-owned resource\n",
            )
        self.assertEqual(validate_pi_distribution(self.source, output / "pi", output), 1)
        (output / "pi/.gitlab-ci.yml").write_text("leaked CI\n")
        with self.assertRaisesRegex(ValueError, "must not be published"):
            validate_pi_distribution(self.source, output / "pi", output)

    def test_distribution_readmes_use_shared_template_and_instance_config(self) -> None:
        self.plugin()
        self.write("README.md", "Source-only overview ${AGENT_TYPO}.\n")
        self.write(".marketplace/readme.json", json.dumps({
            "marketplace": "Example Marketplace",
            "source_url": "https://example.org/source",
            "installation": {
                host: f"Install {host}: `$literal` and ${{AGENT_TYPO}}."
                for host in HOSTS
            },
        }))
        output = self.base / "output"
        before = snapshot(self.source)
        preview = build(self.source, output, dry_run=True, now=NOW)
        self.assertFalse(output.exists())
        built = build(self.source, output, now=NOW)
        self.assertEqual(preview, built)
        self.assertEqual(snapshot(self.source), before)
        for host, name in zip(HOSTS, ("Claude Code", "Codex", "Pi")):
            text = (output / host / "README.md").read_text()
            self.assertTrue(text.startswith(f"# Example Marketplace for {name}\n"))
            self.assertIn(f"Install {host}: `$literal` and ${{AGENT_TYPO}}.", text)
            self.assertIn("https://example.org/source", text)
            self.assertNotIn("Source-only overview", text)
            self.assertFalse((output / host / ".marketplace").exists())
            self.assertIn("README.md", built.trees[HOSTS.index(host)].generated_files)
        self.assertEqual(validate_pi_distribution(self.source, output / "pi", output), 1)
        (output / "pi/.marketplace").mkdir()
        with self.assertRaisesRegex(ValueError, "must not be published"):
            validate_pi_distribution(self.source, output / "pi", output)

    def test_invalid_readme_config_fails_before_output_replacement(self) -> None:
        self.plugin()
        output = self.seed_output()
        before = snapshot(output)
        valid = {
            "marketplace": "Example", "source_url": "https://example.org",
            "installation": dict.fromkeys(HOSTS, "Install here."),
        }
        for config in (None, [], {}, {**valid, "marketplace": " "},
                       {**valid, "installation": {"claude": "Only one host"}},
                       {**valid, "installation": []},
                       {**valid, "source_url": 123}):
            self.write(".marketplace/readme.json", json.dumps(config))
            for dry_run in (True, False):
                with self.subTest(config=config, dry_run=dry_run):
                    with self.assertRaisesRegex(ValueError, "Invalid distribution README"):
                        build(self.source, output, dry_run=dry_run, now=NOW)
                    self.assertEqual(snapshot(output), before)
        self.write(".marketplace/readme.json", "{invalid")
        with self.assertRaisesRegex(ValueError, "Invalid distribution README"):
            build(self.source, output, now=NOW)
        self.assertEqual(snapshot(output), before)

