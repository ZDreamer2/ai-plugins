    def test_output_locations_repeat_replacement_and_active_output_exclusion(self) -> None:
        for location in (
            "default", "external", "nested", "relative", "canonical-link", "safe-parent",
        ):
            with self.subTest(location=location):
                original_source = self.source
                self.source = self.base / location / "source"
                self.source.mkdir(parents=True)
                try:
                    self.plugin()
                    self.write("main/old.bin", b"old")
                    if location == "default":
                        argument = None
                        output = self.source / "@build"
                    elif location == "external":
                        output = self.source.parent / "new-parent" / "output"
                        argument = output
                    elif location == "safe-parent":
                        output = self.source.parent
                        argument = output
                    elif location == "nested":
                        output = self.source / "main/cache/output"
                        argument = output
                    elif location == "relative":
                        output = self.source / "nested/output"
                        argument = output.relative_to(Path.cwd()) if output.is_relative_to(Path.cwd()) else os.path.relpath(output)
                    else:
                        output = self.source / "nested/output"
                        output.mkdir(parents=True)
                        (self.source / "alias").symlink_to("nested/output", target_is_directory=True)
                        argument = self.source / "alias"
                    self.seed_output(output)
                    (output / "ai-plugin.yml").write_text("name: main\n", encoding="utf-8")
                    before = snapshot(self.source, output)
                    first = build(self.source, argument, now=NOW)
                    self.assertEqual(first.plugin_count, 1)
                    self.assertEqual(first.output_dir, output.resolve())
                    self.assertEqual(snapshot(self.source, output), before)
                    self.assertEqual((output / "unrelated.bin").read_bytes(), b"keep me")
                    for host in HOSTS:
                        self.assertEqual((output / host / "main/old.bin").read_bytes(), b"old")
                        self.assertFalse((output / host / "sentinel").exists())
                        self.assertFalse((output / host / "stale-empty").exists())
                        self.assertFalse((output / host / "main/cache/output").exists())
                        self.assertFalse((output / host / "nested/output").exists())
                        self.assertFalse((output / host / "alias").exists())
                        self.assertFalse((output / host / "@build").exists())
                        (output / host / "stale").write_bytes(b"remove")
                    (self.source / "main/old.bin").unlink()
                    self.write("main/new.bin", b"new")
                    second = build(self.source, argument, now=NOW)
                    self.assertEqual(first.plugin_count, second.plugin_count)
                    for host in HOSTS:
                        self.assertFalse((output / host / "main/old.bin").exists())
                        self.assertFalse((output / host / "stale").exists())
                        self.assertEqual((output / host / "main/new.bin").read_bytes(), b"new")
                finally:
                    self.source = original_source

    def test_dangerous_overlap_fails_before_any_input_is_deleted(self) -> None:
        self.plugin()
        self.write("main/README.md", "Original\n")
        for output in (self.source, self.source / "main/.."):
            for dry_run in (False, True):
                with self.subTest(output=output, dry_run=dry_run):
                    before = snapshot(self.source)
                    with self.assertRaises((ValueError, OSError)):
                        build(self.source, output, dry_run=dry_run, now=NOW)
                    self.assertEqual(snapshot(self.source), before)
        # An ancestor output can be safe generally, but its replaced host tree
        # must never contain the source marketplace.
        original = self.source
        self.source = self.base / "overlap/claude/plugins"
        self.source.mkdir(parents=True)
        self.plugin()
        before = snapshot(self.source)
        with self.assertRaises((ValueError, OSError)):
            build(self.source, self.base / "overlap", now=NOW)
        self.assertEqual(snapshot(self.source), before)
        self.source = original

