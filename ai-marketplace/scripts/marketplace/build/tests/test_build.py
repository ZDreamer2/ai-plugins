    def test_git_identity_shared_changes_and_explicit_version(self) -> None:
        self.plugin("auto", "description: Automatic.\nversion: AUTO_VERSION\n")
        self.plugin("fixed", "name: fixed\ndescription: Fixed.\nversion: 9.0\n")
        # Quote a semantic version so YAML retains a string.
        self.write("fixed/ai-plugin.yml", "name: fixed\ndescription: Fixed.\nversion: '9.0'\n")
        self.write("@common/shared.txt", "Shared\n")
        git_env = dict(os.environ, GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull)

        def git(*arguments: str, date: str | None = None) -> None:
            env = git_env.copy()
            if date is not None:
                env.update(GIT_AUTHOR_DATE=date, GIT_COMMITTER_DATE=date)
            subprocess.run(["git", *arguments], cwd=self.source, env=env, check=True,
                           stdout=subprocess.PIPE, stderr=subprocess.PIPE)

        git("init", "-q")
        git("config", "user.name", "Fixture Author")
        git("config", "user.email", "fixture@example.invalid")
        git("add", "auto", "fixed", "@common")
        git("commit", "-qm", "Initial", date="2020-01-02T03:04:05+0000")
        first = build(self.source, now=NOW)
        for host in HOSTS:
            folder = first.output_dir / host
            suffix = ".claude-plugin/plugin.json" if host == "claude" else ".codex-plugin/plugin.json" if host == "codex" else ".pi-plugin/plugin.json"
            auto = json.loads((folder / "auto" / suffix).read_text())
            fixed = json.loads((folder / "fixed" / suffix).read_text())
            self.assertEqual(auto["version"], "20.01.02060405")
            self.assertEqual(fixed["version"], "9.0")
            if host != "pi":
                self.assertEqual(auto["author"], {"name": "Fixture Author"})
                self.assertEqual(fixed["author"], {"name": "Fixture Author"})
        self.write("@common/shared.txt", "Changed shared\n")
        git("add", "@common")
        git("commit", "-qm", "Shared change", date="2021-02-03T04:05:06+0000")
        second = build(self.source, now=NOW)
        self.assertEqual(json.loads((second.output_dir / "claude/auto/.claude-plugin/plugin.json").read_text())["version"], "21.02.03070506")
        self.assertEqual(json.loads((second.output_dir / "claude/fixed/.claude-plugin/plugin.json").read_text())["version"], "9.0")

